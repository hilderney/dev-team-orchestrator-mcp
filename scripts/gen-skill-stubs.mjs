import { writeFile, mkdir } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const dir = join(__dirname, "..", ".zteam", "skills", "roles");
await mkdir(dir, { recursive: true });

function stub(opts) {
  const {
    file,
    title,
    role,
    phase,
    projectType,
    needsUiFlow,
    mission,
    deliver,
    anti,
    artefacts,
    status = "stub",
    note,
  } = opts;
  const lines = [
    `# Skill — ${title}`,
    "",
    `**Role:** ${role} · **Phase:** ${phase} · **projectType:** ${projectType} · **needsUiFlow:** ${needsUiFlow} · **Status:** ${status}`,
    "",
    "## Mission",
    mission,
    "",
    "## Must deliver",
    ...deliver.map((d) => `- ${d}`),
    "",
    "## Anti-patterns",
    ...anti.map((d) => `- ${d}`),
    "",
    "## Artefacts",
    ...artefacts.map((d) => `- ${d}`),
  ];
  if (note) {
    lines.push("", "## Notes", note);
  }
  lines.push("");
  return writeFile(join(dir, file), lines.join("\n"), "utf8");
}

